// Purpose: contract tests for the add-docs-site content generator
//   (tasks 1.1) — tools/gen_docs_content.py must emit one verbatim page
//   module per corpus spec plus a registry module, each page carrying a
//   provenance preamble naming its source path, and fail loudly naming
//   the corpus path when it is missing.
// Responsibilities: run the generator into a temp out dir (never the
//   real src/ tree), byte-diff every emitted content string against its
//   openspec/specs/<name>/spec.md source, cross-check registry coverage
//   against the emitted pages and the corpus directory, and assert the
//   missing-corpus failure mode.
// Rationale: openspec/changes/add-docs-site design D2 — content is
//   generated, never hand-edited, and embedded verbatim, never forked;
//   the byte-diff IS the verbatim enforcement the change names.

// @ts-expect-error node:child_process has no type declarations here
import { spawnSync } from "node:child_process";
// @ts-expect-error node:child_process has no type declarations here
import { spawn as spawnAsync } from "node:child_process";
// @ts-expect-error node:fs has no type declarations here
import { mkdtempSync, readFileSync, readdirSync, rmSync } from "node:fs";// @ts-expect-error node:os has no type declarations here
import { tmpdir } from "node:os";
// @ts-expect-error node:path has no type declarations here
import { join, resolve } from "node:path";
import { expect, it } from "vitest";

const TOOL = resolve("tools/gen_docs_content.py");
const CORPUS = resolve("openspec/specs");

function corpusNames(): string[] {
  return readdirSync(CORPUS).filter((n: string) =>
    readdirSync(join(CORPUS, n)).includes("spec.md"),
  );
}

function extract(text: string, re: RegExp, what: string): string {
  const m = re.exec(text);
  expect(m, what).toBeTruthy();
  return m?.[1] ?? "";
}

function generate(out: string) {
  return spawnSync("python3", [TOOL, "--corpus", CORPUS, "--out", out], {
    encoding: "utf8",
  });
}

// p_docs_content_pages — add-docs-site content.pages: one page module per
// corpus spec + the registry module, nothing else
it("p_docs_content_pages: generates one page module per corpus spec plus registry", () => {
  const out = mkdtempSync(join(tmpdir(), "docs-content-"));
  try {
    const run = generate(out);
    expect(run.status, run.stderr).toBe(0);
    const emitted = readdirSync(out).sort();
    expect(emitted).toEqual(
      [...corpusNames().map((n) => `${n}.ts`), "registry.ts"].sort(),
    );
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}, 60_000);

// p_docs_content_verbatim — add-docs-site content.verbatim: the embedded
// content string is byte-identical to the corpus spec.md (JSON round-trip
// preserves exact bytes), and the provenance preamble names the source
it("p_docs_content_verbatim: page content byte-diffs clean against spec.md with provenance", () => {
  const out = mkdtempSync(join(tmpdir(), "docs-content-"));
  try {
    expect(generate(out).status).toBe(0);
    for (const name of corpusNames()) {
      const emitted = readFileSync(join(out, `${name}.ts`), "utf8");
      const preamble = `// generated by tools/gen_docs_content.py from openspec/specs/${name}/spec.md`;
      expect(emitted, name).toContain(preamble);
      expect(emitted, name).toContain(
        `source=openspec/specs/${name}/spec.md`,
      );
      const raw = extract(
        emitted,
        /export const content = ("(?:[^"\\]|\\.)*");/,
        `${name}: content literal`,
      );
      const verbatim = JSON.parse(raw) as string;
      expect(verbatim, name).toBe(
        readFileSync(join(CORPUS, name, "spec.md"), "utf8"),
      );
    }
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}, 60_000);

// p_docs_content_registry — add-docs-site content.registry: the registry
// lists every page with id, title, statement and one-line description,
// consistent with the page modules
it("p_docs_content_registry: registry lists every page with id, title, statement, description", () => {
  const out = mkdtempSync(join(tmpdir(), "docs-content-"));
  try {
    expect(generate(out).status).toBe(0);
    const raw = extract(
      readFileSync(join(out, "registry.ts"), "utf8"),
      /export const generatedPages = (\[[\s\S]*\]) satisfies GeneratedPage\[\];/,
      "registry array",
    );
    const pages = JSON.parse(raw) as Array<{
      name: string;
      id: string;
      title: string;
      statement: string;
      description: string;
      sourcePath: string;
    }>;
    const names = corpusNames();
    expect(pages.map((p) => p.name).sort()).toEqual(names.sort());
    for (const page of pages) {
      const emitted = readFileSync(
        join(out, `${page.name}.ts`),
        "utf8",
      );
      expect(page.id.length, page.name).toBeGreaterThan(0);
      expect(page.statement, page.name).toMatch(/\bSHALL\b/);
      // humanized title: mechanical derivation, no corpus punctuation
      expect(page.title, page.name).not.toMatch(/[.\-_]/);
      expect(page.title[0], page.name).toBe(page.title[0]?.toUpperCase());
      // one-line description: single line, non-empty prose
      expect(page.description, page.name).not.toMatch(/\n/);
      expect(page.description.length, page.name).toBeGreaterThan(0);
      expect(page.sourcePath, page.name).toBe(
        `openspec/specs/${page.name}/spec.md`,
      );
      // page module carries the same identity as its registry row
      expect(emitted, page.name).toContain(`export const id = ${JSON.stringify(page.id)}`);
      expect(emitted, page.name).toContain(`export const title = ${JSON.stringify(page.title)}`);
    }
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}, 60_000);

// p_docs_content_fail_loud — add-docs-site content.fail_loud: a missing
// corpus exits non-zero and the failure names the path
it("p_docs_content_fail_loud: missing corpus exits non-zero naming the path", () => {
  const missing = join(tmpdir(), "docs-content-no-such-corpus");
  const run = spawnSync(
    "python3",
    [TOOL, "--corpus", missing, "--out", join(tmpdir(), "docs-content-x")],
    { encoding: "utf8" },
  );
  expect(run.status).not.toBe(0);
  const said = `${run.stderr}${run.stdout}`;
  expect(said).toContain("docs-content-no-such-corpus");
}, 60_000);

// Behavioural guard (not a spec row): concurrent generator invocations
// must never expose a torn tree. Two docs test files import-generate
// while a spa build regenerates the same production dir (and ah's
// batched run typechecks src/** mid-flight) — the atomic publication
// order (pages tmp+rename, registry LAST) means any reader sees either
// the whole old or the whole new module set. This test races two
// generators into one fresh dir and verifies the after-state is
// complete: every registry loader resolves to a real file, layout is
// pages + registry only, exit codes clean.
it("concurrent generators publish atomically into a shared out dir", async () => {
  const out = mkdtempSync(join(tmpdir(), "docs-content-race-"));
  const spawn = () =>
    new Promise<number>((res) => {
      const child = spawnAsync("python3", [TOOL, "--corpus", CORPUS, "--out", out]);
      child.on("close", (code: number | null) => res(code ?? -1));
    });
  const codes = await Promise.all([spawn(), spawn(), spawn()]);
  try {
    expect(codes, "every concurrent generator exits 0").toEqual([0, 0, 0]);
    const names = corpusNames().map((n) => `${n}.ts`);
    const emitted = readdirSync(out).sort();
    expect(emitted).toEqual([...names, "registry.ts"].sort());
    // every loader specifier in the registry resolves to a real file
    const registry = readFileSync(join(out, "registry.ts"), "utf8");
    for (const m of registry.matchAll(/import\("\.\/([^"]+)"\)/g)) {
      expect(() => readFileSync(join(out, m[1] ?? ""), "utf8")).not.toThrow();
    }
  } finally {
    rmSync(out, { recursive: true, force: true });
  }
}, 120_000);
