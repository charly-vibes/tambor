#!/usr/bin/env python3
"""Purpose: generate the docs-site content data modules from the spec corpus
  (tambor-gwt task 1, add-docs-site D2; EXCL-001/EXCL-002 carry over from
  gen_ai_docs): one TS page module per openspec/specs/<name>/spec.md with the
  corpus text embedded verbatim under a provenance preamble, plus a registry
  module (id, title, statement, one-line description per page) consumed by
  nav, typed link resolution and RAG front matter.
Responsibilities: parse corpus frontmatter (id + EARS statement) and derive
  the one-line description from the first Purpose sentence and a humanized
  title from the id — mechanically, never fabricated; emit
  src/docs/content/generated/<name>.ts + registry.ts (registry rows as a
  JSON array gated by `satisfies`, so tests and tooling can re-parse it);
  wipe and regenerate the out dir every run; fail loudly naming the path
  when the corpus or a required section is missing.
Rationale: pages are generated, never hand-edited; spec content is embedded
  verbatim, never forked or paraphrased (the byte-diff lives in
  tests/docs-content-generator.test.ts). TS data modules render through
  ordinary tambor views — no runtime markdown parser, no forked rendering.
"""

import argparse
import json
import os
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

FRONT = re.compile(r"^---\n(.*?)\n---", re.DOTALL)
ID = re.compile(r"^id:\s*(.+)$", re.MULTILINE)
STATEMENT = re.compile(r'^statement:\s*"(.*?)"\s*$', re.MULTILINE | re.DOTALL)
PURPOSE = re.compile(r"^## Purpose\s*\n(.+?)(?=\n\s*\n|\n## |\Z)", re.DOTALL | re.MULTILINE)


def fail(msg: str) -> None:
    sys.exit(f"gen-docs-content: {msg}")


def humanize(sid: str) -> str:
    words = [w for w in re.split(r"[._\-]", sid) if w]
    return " ".join(w[0].upper() + w[1:] for w in words)


def parse_spec(path: Path) -> dict:
    text = path.read_text()
    front = FRONT.match(text) or fail(f"{path}: no frontmatter")
    sid = (ID.search(front.group(1)) or fail(f"{path}: no id")).group(1).strip()
    stmt = " ".join((STATEMENT.search(front.group(1)) or fail(f"{path}: no statement")).group(1).split())
    para = PURPOSE.search(text) or fail(f"{path}: no ## Purpose section for the one-line description")
    # one-line description = the first Purpose sentence (B-05): the
    # newline/space squash above turns a sentence-ending ".\n" into
    # ". " so this split terminates exactly on the first sentence
    # boundary — the description never spans two sentences.
    sent = re.sub(r"\s+", " ", para.group(1)).strip().split(". ")[0].rstrip(".")
    name = path.parent.name
    return {
        "id": sid,
        "name": name,
        "title": humanize(sid),
        "statement": stmt,
        "description": sent,
        "sourcePath": f"openspec/specs/{name}/spec.md",
        "group": "reference",  # D7: corpus pages are the reference quadrant
        "content": text,
    }


def page_module(pg: dict) -> str:
    head = (
        f"// generated by tools/gen_docs_content.py from {pg['sourcePath']}"
        " — edit the corpus, not this file\n"
        f"// provenance: id={pg['id']} source={pg['sourcePath']}\n"
    )
    fields = "".join(
        f"export const {k} = {json.dumps(pg[k])};\n"
        for k in ("id", "title", "statement", "description", "sourcePath", "group")
    )
    return head + fields + f"export const content = {json.dumps(pg['content'])};\n"


def page_loaders(pages: list[dict]) -> str:
    # D6: content rides dynamic imports — one static loader per page so
    # esbuild emits per-page chunks; the initial docs chunk carries the
    # registry rows only (add-spa-delivery pattern: static specifiers,
    # no runtime-resolved paths).
    rows = "".join(
        f'  "{pg["name"]}": () => import("./{pg["name"]}.ts"),\n'
        for pg in pages
    )
    return (
        "\n"
        "// one static loader per page (D6): the shell imports bodies through\n"
        "// these so content modules never ride the initial docs chunk\n"
        "export const pageLoaders: Readonly<Record<string, () => Promise<{ content: string }>>> = {\n"
        f"{rows}"
        "};\n"
    )


def registry_module(pages: list[dict]) -> str:
    keep = ("name", "id", "title", "statement", "description", "sourcePath", "group")
    meta = [{k: pg[k] for k in keep} for pg in pages]
    rows = json.dumps(meta, separators=(",", ":"))
    return (
        "// generated by tools/gen_docs_content.py — edit the corpus, not this file\n"
        "// registry of the generated reference pages: nav, typed link\n"
        "// resolution and RAG front matter consume it; rows are JSON so\n"
        "// tests and tooling can re-parse them (docs-content-generator.test.ts)\n"
        "export interface GeneratedPage {\n"
        "  name: string;\n"
        "  id: string;\n"
        "  title: string;\n"
        "  statement: string;\n"
        "  description: string;\n"
        "  sourcePath: string;\n"
        "  group: string;\n"
        "}\n"
        f"export const generatedPages = {rows} satisfies GeneratedPage[];\n"
    ) + page_loaders(pages)


def atomic_write(path: Path, text: str) -> None:
    # tmp + os.replace: Linux rename over an existing path is atomic —
    # a concurrent reader (the CI-red 42082454763 family: p_strict/
    # p_typescript typecheck src/** while a heavy build regenerates
    # these modules) sees either the whole old file or the whole new
    # one, never a truncated window. The tmp name carries the pid:
    # concurrent generator invocations (two docs test files import-
    # generating while a spa build regenerates the same tree) must
    # never share one tmp file.
    tmp = path.with_name(f"{path.name}.{os.getpid()}.tmp")
    # Same-corpus assumption (B-02): the module text is a pure function
    # of the corpus page — when regeneration is byte-identical to what
    # is on disk, skip the write so mtimes stay stable (no churn, no
    # downstream rebuild/watcher triggers). A real corpus change always
    # changes the text, so the guard never masks one; publication
    # ordering is preserved (registry still written last below, and
    # unchanged files keep their tmp+replace behaviour untouched).
    if path.is_file() and path.read_text() == text:
        return
    tmp.write_text(text)
    os.replace(tmp, path)


def emit(corpus: Path, out: Path) -> int:
    if not corpus.is_dir():
        fail(f"corpus not found: {corpus} — the corpus is the source of truth")
    specs = sorted(corpus.glob("*/spec.md"))
    if not specs:
        fail(f"no spec.md under {corpus}")
    pages = [parse_spec(p) for p in specs]
    # generated, never hand-edited: the tool owns the whole out dir, so a
    # renamed corpus spec can never leave a stale page behind.
    # Publication order matters for concurrent readers: pages first
    # (each atomically), registry LAST — the registry is the only entry
    # point to page modules (static loaders), so no reader can ever
    # resolve a specifier the swap has not already materialised. The
    # post-sweep retires removed pages only after the new registry is
    # live. (Replaces the old rmtree+plain-write, which opened a
    # torn-tree window that transiently failed p_strict in the ah
    # batch run, push 2026-11-05.)
    out.mkdir(parents=True, exist_ok=True)
    for pg in pages:
        atomic_write(out / f"{pg['name']}.ts", page_module(pg))
    atomic_write(out / "registry.ts", registry_module(pages))
    keep = {f"{pg['name']}.ts" for pg in pages} | {"registry.ts"}
    for stale in out.iterdir():
        # never sweep an in-flight tmp of a concurrent generator
        if not stale.is_file() or stale.name.endswith(".tmp"):
            continue
        if stale.name not in keep:
            stale.unlink(missing_ok=True)
    return len(pages)


def main() -> None:
    p = argparse.ArgumentParser(description="emit docs-site content modules from the spec corpus")
    p.add_argument("--corpus", type=Path, default=ROOT / "openspec" / "specs", help="corpus dir")
    p.add_argument("--out", type=Path, default=ROOT / "src" / "docs" / "content" / "generated", help="out dir")
    a = p.parse_args()
    print(f"gen-docs-content: {emit(a.corpus, a.out)} page modules + registry.ts under {a.out}")


if __name__ == "__main__":
    main()
