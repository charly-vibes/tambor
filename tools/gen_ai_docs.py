#!/usr/bin/env python3
"""Purpose: generate AI-facing documentation from the spec corpus
  (tambor-cie.4, EXCL-001/EXCL-002): ai/llms.txt plus one ai/specs/<name>.md
  page per openspec/specs/<name>/spec.md, deployed with the Pages artifact.
Responsibilities: read every dual-format spec.md, extract the frontmatter id
  and EARS statement, emit an llms.txt index linking each per-spec page, and
  emit each page as the corpus spec.md embedded verbatim under a generated
  provenance preamble. Fail loudly if the corpus is missing.
Rationale: the repo's product is a machine-readable corpus, yet no AI entry
  point existed. Pages are generated, never hand-edited; spec content is
  embedded verbatim (linked to its source path), never forked or paraphrased.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "openspec" / "specs"
OUT = ROOT / "ai"

FRONT = re.compile(r'^---\n(.*?)\n---', re.DOTALL)
ID = re.compile(r'^id:\s*(.+)$', re.MULTILINE)
STATEMENT = re.compile(r'^statement:\s*"(.*?)"\s*$', re.MULTILINE | re.DOTALL)


def fail(msg: str) -> None:
    sys.exit(f"gen-ai-docs: {msg}")


def parse_spec(path: Path) -> tuple[str, str]:
    text = path.read_text()
    front = FRONT.match(text) or fail(f"{path}: no frontmatter")
    sid = (ID.search(front.group(1)) or fail(f"{path}: no id")).group(1).strip()
    stmt = " ".join((STATEMENT.search(front.group(1)) or fail(f"{path}: no statement")).group(1).split())
    return sid, stmt


def main() -> None:
    if not SPECS.is_dir():
        fail("openspec/specs/ not found — the corpus is the source of truth")
    specs = sorted(SPECS.glob("*/spec.md"))
    if not specs:
        fail("no spec.md files under openspec/specs/")

    (OUT / "specs").mkdir(parents=True, exist_ok=True)

    lines = [
        "# tambor — llms.txt",
        "",
        "> tambor is a strict-TypeScript, mobile-first UI library: views are plain",
        "> values, handlers are pure functions returning effects, and components edit",
        "> parent state only through derived paths. This index is generated from the",
        "> specodelic corpus in openspec/specs/ — the single source of truth.",
        "> Human/demo site: https://charly-vibes.github.io/tambor/",
        "",
        "## Specs (one page per corpus spec, full spec.md embedded)",
        "",
    ]
    for path in specs:
        name = path.parent.name
        sid, stmt = parse_spec(path)
        page = OUT / "specs" / f"{name}.md"
        page.write_text(
            f"<!-- generated by tools/gen_ai_docs.py from openspec/specs/{name}/spec.md — edit the corpus, not this file -->\n\n"
            f"# {sid}\n\n{stmt}\n\n---\n\n" + path.read_text()
        )
        lines.append(f"- [{sid}](specs/{name}.md): {stmt}")

    (OUT / "llms.txt").write_text("\n".join(lines) + "\n")
    print(f"gen-ai-docs: {len(specs)} spec pages + llms.txt under ai/")


if __name__ == "__main__":
    main()
